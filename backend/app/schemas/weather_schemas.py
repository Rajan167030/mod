"""
Pydantic schemas for Weather API and Location endpoints.
All thresholds and data are illustrative demonstration values.
"""
from datetime import datetime
from typing import Optional, List, Dict, Any
from pydantic import BaseModel, Field, field_validator


# ==============================
# Location Schemas
# ==============================
class LocationCreate(BaseModel):
    scenario_id: str
    name: str = Field(..., min_length=2, max_length=255)
    latitude: float = Field(..., ge=-90, le=90)
    longitude: float = Field(..., ge=-180, le=180)
    location_type: str = Field(default="POI")
    metadata_json: Optional[Dict[str, Any]] = None

    @field_validator("location_type")
    @classmethod
    def validate_location_type(cls, v: str) -> str:
        allowed = {"BASE", "WAYPOINT", "WEATHER_STATION", "POI", "LOGISTICS_HUB"}
        if v.upper() not in allowed:
            raise ValueError(f"location_type must be one of {allowed}")
        return v.upper()


class LocationResponse(BaseModel):
    id: str
    scenario_id: str
    name: str
    latitude: float
    longitude: float
    location_type: str
    metadata_json: Optional[Dict[str, Any]] = None
    created_at: datetime

    class Config:
        from_attributes = True


class GeoJSONProperties(BaseModel):
    id: str
    name: str
    location_type: str
    scenario_id: str
    metadata: Optional[Dict[str, Any]] = None
    weather_status: Optional[str] = None


class GeoJSONFeature(BaseModel):
    type: str = "Feature"
    geometry: Dict[str, Any]
    properties: GeoJSONProperties


class GeoJSONFeatureCollection(BaseModel):
    type: str = "FeatureCollection"
    features: List[GeoJSONFeature] = []


# ==============================
# Weather Data Schemas
# ==============================
class WeatherDataPoint(BaseModel):
    """A single normalized weather observation or forecast data point."""
    forecast_timestamp: datetime
    temperature_celsius: Optional[float] = None
    precipitation_mm: Optional[float] = None
    wind_speed_kmh: Optional[float] = None
    weather_condition: Optional[str] = None
    wind_gust_kmh: Optional[float] = None
    wind_direction_deg: Optional[float] = None
    visibility_m: Optional[float] = None
    cloud_cover_pct: Optional[float] = None
    relative_humidity_pct: Optional[float] = None
    pressure_hpa: Optional[float] = None
    dew_point_celsius: Optional[float] = None
    units: Dict[str, str] = Field(default_factory=lambda: {
        "temperature": "°C",
        "precipitation": "mm",
        "wind_speed": "km/h"
    })


class WeatherCurrentResponse(BaseModel):
    """Current weather for a single location."""
    location_id: str
    location_name: str
    latitude: Optional[float] = None
    longitude: Optional[float] = None
    provider: str = "open-meteo"
    data: Optional[WeatherDataPoint] = None
    freshness: str = "UNKNOWN"
    retrieved_at: Optional[datetime] = None
    data_source: str = "Open-Meteo (open-source weather API)"
    disclaimer: str = "Illustrative demonstration data — not for operational decisions."


class WeatherForecastResponse(BaseModel):
    """Hourly forecast for a single location."""
    location_id: str
    location_name: str
    latitude: Optional[float] = None
    longitude: Optional[float] = None
    provider: str = "open-meteo"
    forecast_points: List[WeatherDataPoint] = []
    freshness: str = "UNKNOWN"
    retrieved_at: Optional[datetime] = None
    data_source: str = "Open-Meteo (open-source weather API)"
    disclaimer: str = "Illustrative demonstration data — not for operational decisions."


# ==============================
# Weather Threshold Configuration
# ==============================
class WeatherThresholdConfig(BaseModel):
    """
    Configurable demonstration thresholds for weather alert rules.
    These are illustrative and editable — not real aviation/military safety standards.
    """
    wind_speed_warning_kmh: float = 45.0
    wind_speed_critical_kmh: float = 65.0
    precipitation_warning_mm: float = 5.0
    precipitation_critical_mm: float = 15.0
    temperature_low_warning_celsius: float = -10.0
    temperature_low_critical_celsius: float = -25.0


# ==============================
# Weather Alert Schemas
# ==============================
class WeatherAlertItem(BaseModel):
    """Structured weather alert generated by the rules engine."""
    location_id: str
    location_name: str
    forecast_timestamp: datetime
    variable: str  # "wind_speed", "precipitation", "temperature"
    observed_value: float
    threshold: float
    severity: str  # "INFO", "WARNING", "CRITICAL"
    freshness: str  # "FRESH", "STALE", "UNKNOWN"
    explanation: str
    source_timestamp: Optional[datetime] = None
    # "forecast" = live provider data; "exercise" = simulated inject inside a training exercise
    source: str = "forecast"


class WeatherAlertsResponse(BaseModel):
    """All weather alerts for a scenario."""
    scenario_id: str
    alerts: List[WeatherAlertItem] = []
    total_alerts: int = 0
    critical_count: int = 0
    warning_count: int = 0
    info_count: int = 0
    freshness_summary: str = "UNKNOWN"
    thresholds_used: Optional[WeatherThresholdConfig] = None
    disclaimer: str = "Alerts based on illustrative demonstration thresholds — not operational safety standards."


# ==============================
# Weather Refresh Schemas
# ==============================
class WeatherRefreshRequest(BaseModel):
    location_id: Optional[str] = None
    scenario_id: Optional[str] = None

    @field_validator("scenario_id", "location_id", mode="before")
    @classmethod
    def at_least_one(cls, v, info):
        return v


class WeatherRefreshResponse(BaseModel):
    success: bool = True
    refreshed_locations: int = 0
    status: str = "completed"
    message: str = ""
    errors: List[str] = []


# ==============================
# Weather Scheduling Constraint Schemas
# ==============================
class WeatherConstraint(BaseModel):
    """A scheduling constraint derived from a weather alert."""
    alert: WeatherAlertItem
    constraint_type: str  # "HARD_BLACKOUT", "SOFT_PENALTY", "REVIEW_FLAG"
    affected_resource_ids: List[str] = []
    affected_task_ids: List[str] = []
    penalty_weight: Optional[int] = None
    explanation: str = ""


class WeatherConstraintsResponse(BaseModel):
    """Weather-derived constraints for the scheduling engine."""
    scenario_id: str
    constraints: List[WeatherConstraint] = []
    total_constraints: int = 0
    hard_constraints: int = 0
    soft_constraints: int = 0
    review_flags: int = 0
    weather_data_available: bool = False
    freshness_summary: str = "UNKNOWN"
    fallback_policy: str = "Conservative — stale/unknown data treated as WARNING, requires human review."


# ==============================
# METAR / TAF (NOAA Aviation Weather Center)
# ==============================
class MetarCloudLayer(BaseModel):
    cover: str
    base_ft: Optional[int] = None


class MetarObservation(BaseModel):
    """Latest METAR (and TAF if issued) for the reporting station nearest a location."""
    station_id: str
    station_name: Optional[str] = None
    latitude: float
    longitude: float
    elevation_m: Optional[float] = None
    distance_km: float
    observed_at: Optional[datetime] = None
    raw_metar: str
    raw_taf: Optional[str] = None
    flight_category: Optional[str] = None  # VFR / MVFR / IFR / LIFR
    temperature_celsius: Optional[float] = None
    dew_point_celsius: Optional[float] = None
    wind_direction_deg: Optional[float] = None  # None when variable (VRB)
    wind_speed_kt: Optional[float] = None
    wind_gust_kt: Optional[float] = None
    visibility: Optional[str] = None  # as reported by AWC, statute miles ("10+" possible)
    altimeter_hpa: Optional[float] = None
    clouds: List[MetarCloudLayer] = []


class MetarResponse(BaseModel):
    location_id: str
    location_name: str
    provider: str = "NOAA Aviation Weather Center"
    search_radius_km: float
    observation: Optional[MetarObservation] = None
    message: Optional[str] = None
